package com.gainscha.jzint;

/**
 * @author mxlei
 * @date 2020/12/19
 */
public class BitmapResult {

    public byte[] pixels;
    public int width;
    public int height;

    public byte[] getPixels() {
        return pixels;
    }

    public void setPixels(byte[] pixels) {
        this.pixels = pixels;
    }

    public int getWidth() {
        return width;
    }

    public void setWidth(int width) {
        this.width = width;
    }

    public int getHeight() {
        return height;
    }

    public void setHeight(int height) {
        this.height = height;
    }
}
